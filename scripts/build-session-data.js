// One-off: turn the raw Deepgram result + raw Gemini notes into the two data
// modules the dashboard imports. Reshapes the transcript to the exact portfolio
// types (drops Deepgram extras like words/num_words) and sanitizes the notes for
// the portfolio renderer (strips the Mermaid diagram it can't render).
const fs = require("fs");

const LIB = "/Users/ethanorr/Documents/Projects/Portfolio/src/components/scroll-experience/projects/recorder/dashboard/lib";

// ---- Transcript: reshape to { speaker, start, end, sentences:[{text,start,end}] }
const dg = JSON.parse(fs.readFileSync("/tmp/dg_transcript.json", "utf8"));
const alt = dg.results.channels[0].alternatives[0];
const paras = (alt.paragraphs?.paragraphs || []).map((p) => ({
  speaker: p.speaker,
  start: round(p.start),
  end: round(p.end),
  sentences: (p.sentences || []).map((s) => ({ text: s.text.trim(), start: round(s.start), end: round(s.end) })),
}));

function round(n) {
  return typeof n === "number" ? Math.round(n * 100) / 100 : n;
}

const paraLines = paras.map((p) => "    " + JSON.stringify(p)).join(",\n");
const transcriptTs = `import type { DeepgramResult } from "./dashboardTypes";

// REAL Deepgram transcript (model nova-3, diarized, smart-formatted) of
// public/audio/session.mp3 — "The Future of Astronomy", Edward C. Pickering's
// 1909 address (LibriVox public-domain reading). Generated by
// scripts/build-session-data.js with CHE's exact Deepgram options; word-level
// timings stripped (sentence granularity is what the dashboard renders). Single
// speaker (the reader), so every paragraph is Speaker 0.
export const PICKERING_TRANSCRIPT: DeepgramResult = {
  results: {
    channels: [
      {
        alternatives: [
          {
            transcript: ${JSON.stringify(alt.transcript)},
            confidence: ${alt.confidence ?? 1},
            paragraphs: {
              paragraphs: [
${paraLines},
              ],
            },
          },
        ],
      },
    ],
  },
};
`;
fs.writeFileSync(LIB + "/pickeringTranscript.ts", transcriptTs);

// ---- Notes: strip the Mermaid diagram (portfolio can't render it), tidy gaps.
let notes = fs.readFileSync("/tmp/notes_raw.md", "utf8");
const hadMermaid = /```mermaid[\s\S]*?```/.test(notes);
notes = notes.replace(/\n*```mermaid[\s\S]*?```\n*/g, "\n\n"); // drop diagram blocks
notes = notes.replace(/\n{3,}/g, "\n\n").trim() + "\n";

const esc = notes.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
const notesTs = `// REAL AI notes — generated by gemini-2.5-pro with CHE's exact aiSummary
// SYSTEM_PROMPT (firebase/functions/src/aiSummary.ts) against the real Deepgram
// transcript. Sanitized for the portfolio renderer: the one Mermaid diagram is
// stripped (react-markdown + remark-gfm has no Mermaid). {{ts:M:SS}} tokens are
// turned into seek pills by AiNotesBody. Generated by scripts/build-session-data.js.
export const PICKERING_NOTES = \`${esc}\`;
`;
fs.writeFileSync(LIB + "/pickeringNotes.ts", notesTs);

console.log(`transcript: ${paras.length} paragraphs, ${transcriptTs.split("\n").length} lines`);
console.log(`notes: mermaidStripped=${hadMermaid}, ${notes.length} chars, ${(notes.match(/\{\{ts:/g) || []).length} ts-pills, ${(notes.match(/^#{2,4} /gm) || []).length} headings`);
console.log(`still has mermaid? ${/mermaid/i.test(notes)} | backticks? ${/`/.test(notes)}`);
